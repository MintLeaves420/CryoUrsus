import urllib.request
import json
import time
import pytest

def is_server_running(url: str = "http://127.0.0.1:8000/api/profiles") -> bool:
    try:
        with urllib.request.urlopen(url, timeout=1.0) as resp:
            return resp.status == 200
    except Exception:
        return False

@pytest.mark.skipif(not is_server_running(), reason="Live backend server is not running on port 8000")
def test_live_server_full_cycle():
    base = "http://127.0.0.1:8000/api"

    # 1. Create shipment
    create_payload = json.dumps({
        "profile_id": "demo-profile-standard-mab",
        "vial_count": 9,
        "sensor_count": 4,
        "scenario": "normal",
        "destination_label": "Live Demo Test Facility",
    }).encode("utf-8")
    req = urllib.request.Request(f"{base}/shipments", data=create_payload, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req) as resp:
        shp = json.loads(resp.read().decode())
    shp_id = shp["id"]
    assert shp["status"] == "created"

    # 2. Start simulation
    req_start = urllib.request.Request(f"{base}/shipments/{shp_id}/start", data=b"{}", headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req_start) as resp:
        assert resp.status == 200

    time.sleep(3.5)

    # 3. Verify readings streaming
    with urllib.request.urlopen(f"{base}/shipments/{shp_id}/readings") as resp:
        readings = json.loads(resp.read().decode())
    assert readings["total"] > 0

    # 4. Change scenario to gradual warming
    scen_payload = json.dumps({"scenario": "gradual_warming"}).encode("utf-8")
    req_scen = urllib.request.Request(f"{base}/shipments/{shp_id}/scenario", data=scen_payload, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req_scen) as resp:
        assert resp.status == 200

    time.sleep(7.0)

    # 5. Check alerts generated by excursion
    with urllib.request.urlopen(f"{base}/alerts?shipment_id={shp_id}") as resp:
        alerts = json.loads(resp.read().decode())
    assert len(alerts) >= 1
    assert any(a["type"] == "upper_limit" for a in alerts)

    # 6. Submit assessment
    asm_payload = json.dumps({
        "review_status": "reviewed",
        "reviewer_label": "Quality Assurance Reviewer",
        "review_note": "Observed and validated upper limit breach during transit.",
    }).encode("utf-8")
    req_asm = urllib.request.Request(f"{base}/shipments/{shp_id}/assessment", data=asm_payload, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req_asm) as resp:
        asm = json.loads(resp.read().decode())
    assert asm["review_status"] == "reviewed"
    assert asm["demo_score"] is not None

    # 7. Simulated NFC transfer
    req_nfc = urllib.request.Request(f"{base}/shipments/{shp_id}/nfc-transfer", data=b"{}", headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req_nfc) as resp:
        nfc = json.loads(resp.read().decode())
    assert nfc["status"] == "success"
    assert nfc["records_transferred"] > 0

    # 8. Report PDF generation
    with urllib.request.urlopen(f"{base}/shipments/{shp_id}/report.pdf") as resp:
        pdf_bytes = resp.read()
    assert len(pdf_bytes) > 1000
    assert pdf_bytes.startswith(b"%PDF")

    # 9. End shipment
    req_end = urllib.request.Request(f"{base}/shipments/{shp_id}/end", data=b"{}", headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req_end) as resp:
        ended_shp = json.loads(resp.read().decode())
    assert ended_shp["status"] == "completed"

if __name__ == "__main__":
    test_live_server_full_cycle()
    print("Live Server End-to-End Cycle: ALL CHECKS PASSED")
